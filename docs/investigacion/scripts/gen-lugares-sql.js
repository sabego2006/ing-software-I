#!/usr/bin/env node
// P1 · Genera V21__lugares_canonicos.sql (tabla places + place_aliases) desde lugares-canonicos.json.
//
//   node gen-lugares-sql.js <ruta-de-salida.sql>
//
// Solo entran los lugares CON coordenada (places.lat/lng son NOT NULL). La unicidad se exige sobre el
// nombre normalizado (igual que PlaceName.normalize del backend), así que si dos lugares o alias
// chocan al normalizar, el alias que choca se OMITE y se avisa por consola: el nombre del lugar nunca
// se omite, y si choca un nombre el script falla. Determinista: misma entrada, mismo .sql.
'use strict';
const fs = require('fs');
const path = require('path');

const RAIZ = path.resolve(__dirname, '..', '..', '..');
const ENTRADA = path.join(RAIZ, 'docs', 'investigacion', 'lugares', 'lugares-canonicos.json');
const salida = process.argv[2];
if (!salida) { console.error('uso: node gen-lugares-sql.js <ruta-de-salida.sql>'); process.exit(2); }

const norm = s => String(s).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/\./g, '').replace(/\s+/g, ' ').trim();
const q = s => "'" + String(s).replace(/'/g, "''") + "'";

const lugares = JSON.parse(fs.readFileSync(ENTRADA, 'utf8')).filter(l => l.lat != null && l.lng != null);
const usados = new Map(); // normalizado -> descripción de quién lo tiene
const omitidos = [];
for (const l of lugares) {
  const n = norm(l.nombre);
  if (usados.has(n)) throw new Error(`Nombre repetido al normalizar: "${l.nombre}" choca con ${usados.get(n)}`);
  usados.set(n, `nombre de ${l.slug}`);
}
const aliases = [];
// Un alias que comparten varios lugares es ambiguo (p. ej. "Calle 3" de los tres homonimos): no se
// asigna a ninguno, para que la busqueda legada por nombre no elija uno al azar.
const veces = new Map();
for (const l of lugares) for (const n of new Set(l.alias.map(norm))) veces.set(n, (veces.get(n) || 0) + 1);
for (const l of lugares) {
  for (const a of l.alias) {
    const n = norm(a);
    if (n === norm(l.nombre)) continue; // solo cambia tildes o mayusculas: el nombre ya lo cubre
    if (veces.get(n) > 1) { omitidos.push(`${l.slug}: "${a}" (ambiguo: lo comparten ${veces.get(n)} lugares)`); continue; }
    if (usados.has(n)) { omitidos.push(`${l.slug}: "${a}" (choca con ${usados.get(n)})`); continue; }
    usados.set(n, `alias de ${l.slug}`);
    aliases.push({ slug: l.slug, alias: a, n });
  }
}

const out = [];
out.push(`-- SCRUM-8 / P1: lugares canonicos con coordenada (tabla places + place_aliases).
--
-- Fuente: docs/investigacion/lugares/lugares-canonicos.json de la carpeta del curso (P0, 2026-11-08),
-- generado por docs/investigacion/scripts/gen-lugares-sql.js. NO editar a mano: se regenera.
-- Solo entran los lugares con coordenada (${lugares.length}); los que P0 dejo sin coordenada no se pueden
-- buscar por geometria y se agregan en una migracion nueva cuando alguien aporte el dato.
--
-- name_normalized y alias_normalized siguen la misma regla que PlaceName.normalize del dominio (NFD sin
-- diacriticos, minusculas, sin puntos, espacios colapsados) y son UNIQUE entre si por separado; el
-- generador ademas garantiza que ningun alias choque con el nombre de otro lugar. route_neighborhoods NO
-- se toca: sigue siendo lo que se muestra en "Por donde pasa".
CREATE TABLE places (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            VARCHAR(120)     NOT NULL,
    name            VARCHAR(140)     NOT NULL,
    name_normalized VARCHAR(140)     NOT NULL,
    lat             DOUBLE PRECISION NOT NULL,
    lng             DOUBLE PRECISION NOT NULL,
    created_at      TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CONSTRAINT uq_places_slug UNIQUE (slug),
    CONSTRAINT uq_places_name_normalized UNIQUE (name_normalized),
    CONSTRAINT ck_places_lat CHECK (lat BETWEEN -90 AND 90),
    CONSTRAINT ck_places_lng CHECK (lng BETWEEN -180 AND 180)
);

CREATE TABLE place_aliases (
    place_id         BIGINT       NOT NULL,
    alias            VARCHAR(140) NOT NULL,
    alias_normalized VARCHAR(140) NOT NULL,
    PRIMARY KEY (place_id, alias_normalized),
    CONSTRAINT uq_place_aliases_alias_normalized UNIQUE (alias_normalized),
    CONSTRAINT fk_place_aliases_place FOREIGN KEY (place_id) REFERENCES places (id) ON DELETE CASCADE
);

INSERT INTO places (slug, name, name_normalized, lat, lng) VALUES`);
out.push(lugares.map(l => `    (${q(l.slug)}, ${q(l.nombre)}, ${q(norm(l.nombre))}, ${l.lat}, ${l.lng})`).join(',\n') + ';');
out.push('');
if (aliases.length) {
  out.push('INSERT INTO place_aliases (place_id, alias, alias_normalized)');
  out.push('SELECT p.id, v.alias, v.alias_normalized');
  out.push('  FROM (VALUES');
  out.push(aliases.map(a => `    (${q(a.slug)}, ${q(a.alias)}, ${q(a.n)})`).join(',\n'));
  out.push('  ) AS v(slug, alias, alias_normalized)');
  out.push('  JOIN places p ON p.slug = v.slug;');
  out.push('');
}
fs.writeFileSync(salida, out.join('\n'));
console.log(`places: ${lugares.length} | aliases: ${aliases.length} | alias omitidos por choque: ${omitidos.length}`);
omitidos.forEach(o => console.log('  - ' + o));
